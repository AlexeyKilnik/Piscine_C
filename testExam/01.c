#include <unistd.h>

int main(void)
{
	char str[] = "C0o1d2e3!";
	// str[j] = str[i];
	// i = 2
	// j = 1
	int i;
	int j;

	i = 0;
	j = 0;

	while (str[i] != '\0')
	{
		if (str[i] < '0' || str[i] > '9')
		{
			str[j] = str[i];
			//write(1, str[i],1);
			j++;
		}
		i++;	
	}
	str[j] = '\0';
	write(1, str, j);
	write(1, "\n", 1);
	return (1);
}
