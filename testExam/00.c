
/*
 * ЗАДАЧА №1 — БОЛЬШИЕ БУКВЫ
 *
 * Сложность: легкая
 *
 * УСЛОВИЕ:
 *
 * Напиши программу, которая переводит все маленькие
 * английские буквы в строке в большие.
 *
 * Программа должна содержать функцию main().
 *
 * Исходная строка:
 *
 * "Hello, Alexey! 42"
 *
 * ОЖИДАЕМЫЙ РЕЗУЛЬТАТ:
 *
 * HELLO, ALEXEY! 42
 *
 *
 * ОЖИДАЕМАЯ ЛОГИКА:
 *
 * 1. Создай массив символов с исходной строкой.
 *
 * 2. Создай переменную для перемещения по массиву.
 *
 * 3. Пройди по строке от первого символа до '\0'.
 *
 * 4. Для каждого символа проверь:
 *    - Если это маленькая английская буква
 *      от 'a' до 'z', преобразуй ее в большую.
 *    - Если это большая буква, цифра, пробел
 *      или знак препинания, оставь без изменений.
 *
 * 5. Выведи полученную строку в терминал.
 *
 * 6. Заверши вывод переводом строки.
 *
 */

#include <unistd.h>

int main(void)
{
	char str[] = "Hello, Alexey! 42";
	int i;

	i = 0;

	while (str[i] != '\0')
	{
		if (str[i] >= 'a' && str[i] <= 'z')
		{
			str[i] = str[i] - 32;
			write(1, &str[i],1);
			i++;
		}
		else
		{
			write(1, &str[i], 1);
			i++;
		}
	}
	write(1,"\n" , 1);
	return (1);	
}

