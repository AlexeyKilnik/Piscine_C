/*
ЗАДАНИЕ C06 ex01 — ft_print_params

Выведи все переданные пользователем аргументы в исходном порядке.
Каждый аргумент — на отдельной строке. Имя программы не выводи.

Запуск: ./program CSKA Arsenal Zenit
Вывод:
CSKA
Arsenal
Zenit

ЛОГИКА
1. Создай целочисленный индекс i.
2. Первый пользовательский аргумент находится в argv[1].
3. Повторяй действия, пока i < argc.
4. Выведи строку argv[i] через ft_putstr, затем перевод строки.
5. Увеличь i на 1.
6. После цикла верни 0 из main.

Проверки: без аргументов; один аргумент; три аргумента;
фраза в кавычках; пустой аргумент "".
Не используй i <= argc: argv[argc] не является строкой.
ft_putstr уже готова; внешняя функция для вывода — только write.
*/

#include <unistd.h>

void ft_putstr(char *str)
{
    int i;

    i = 0;
    while (str[i] != '\0')
    {
        write(1, &str[i], 1);
        i = i + 1;
    }
}

int main(int argc, char **argv)
{
    /* TODO: напиши решение по шагам из комментария. */
    int i;

    i = 1;

    while (i < argc)
    {
        ft_putstr(argv[i]);
        write (1, "\n",1);
        i++;
    }

    return (0);
}
