/*
ЗАДАНИЕ C06 ex02 — ft_rev_params

Выведи пользовательские аргументы в обратном порядке.
Каждый аргумент — на отдельной строке. Имя программы не выводи.
Буквы внутри каждого слова должны остаться в прежнем порядке.

Запуск: ./program CSKA Arsenal Zenit NULL
Вывод:
Zenit
Arsenal
CSKA

ЛОГИКА
1. Последний аргумент имеет индекс argc - 1.
2. Начни обход с этого индекса.
3. Повторяй, пока индекс больше 0.
4. Выведи argv[i], затем перевод строки.
5. Уменьши i на 1.
6. После цикла верни 0 из main.

Перед запуском выпиши значения i для трёх аргументов.
Проверь также запуск без аргументов: цикл не должен начаться.
ft_putstr уже готова; внешняя функция для вывода — только write.
*/

#include <unistd.h>

void ft_putstr(char *str)
{
    int i;

    i = 0;
    while (str[i] != '\0')
    {
        write(1, &str[i], 1);
        i = i + 1;
    }
}

int main(int argc, char **argv)
{
    /* TODO: напиши решение по шагам из комментария. */
    int i;

    i = argc - 1;

    while (i > 0)
    {
        ft_putstr(argv[i]);
        write (1, "\n", 1);
        i--;
    }

    return (0);
}
