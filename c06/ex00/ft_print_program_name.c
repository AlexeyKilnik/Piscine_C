/*
ЗАДАНИЕ C06 ex00 — ft_print_program_name

Напиши программу, которая выводит своё имя из argv[0].
После имени должен быть один перевод строки.
Не пиши имя программы вручную: при другом имени файла оно изменится.

Пример запуска: ./program CSKA Arsenal
Ожидаемый вывод: ./program и перевод строки.
Слова CSKA и Arsenal здесь не выводятся.

ЛОГИКА
1. Сохрани заголовок main(int argc, char **argv).
2. Проверь argc > 0: тогда существует строка argv[0].
3. Передай argv[0] в готовую ft_putstr.
4. Выведи перевод строки через write.
5. Заверши main с return (0).

ft_putstr ниже уже готова. Вспомни её из C04 и объясни цикл.
Внешняя функция для вывода: только write.
У этой программы main уже находится в данном файле.
*/

#include <unistd.h>

void ft_putstr(char *str)
{
    int i;

    i = 0;
    while (str[i] != '\0')
    {
        write(1, &str[i], 1);
        i = i + 1;
    }
}

int main(int argc, char **argv)
{
    /* TODO: напиши решение по шагам из комментария. */
    if (argc > 0)
    {
        ft_putstr(argv[0]);
    }

    write (1, "\n", 1);     

    return (0);
}