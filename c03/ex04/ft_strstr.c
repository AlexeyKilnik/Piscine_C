// Иван → Алексей → Максим → Алексей → Сергей → Андрей
// Алексей → Сергей
//
// Ожидаемая логика
// 1. Берём первую позицию основной строки str.
// 2. Предполагаем: «А вдруг to_find начинается именно здесь?»
// 3. Начинаем сравнивать символы:
// str[i] с to_find[0];
// str[i + 1] с to_find[1];
// str[i + 2] с to_find[2];
// и так далее.
// 4. Пока символы совпадают — продолжаем проверку.
// 5. Если дошли до конца to_find, значит вся искомая строка совпала — возвращаем адрес &str[i].
// 6. Если встретили несовпадение — текущая попытка не подошла.
// 7. Сдвигаем начало поиска на один символ вправо: i++.
// 8. Повторяем всё снова.
// 9. сли дошли до конца str и полного совпадения так и не нашли — возвращаем 0.
//
// i — откуда мы сейчас пробуем начать поиск.
// j — насколько далеко мы уже проверили совпадение.
//
// str     = "abxcv"
// to_find = "abc"
// 
// Почему нужны i и j
// str     = "xxcatxx"
// to_find = "cat"

// i = 2 - c
// str[i + j] == to_find[j]
// j = 0
// str[2 + 0] == to_find[0]
// j++
// str[2 + 1] == to_find[1]
// j++
// str[2 + 2] == to_find[2]

#include <stdio.h>

char	*ft_strstr(char *str, char *to_find)
{
	int i;
	int j;

	j = 0;
	i = 0;

	while(str[i] != '\0')
	{
		while(str[i + j] != '\0' && to_find[j] != '\0' && str[i + j] == to_find[j])
		{
			j++;
		}
		if (to_find[j] == '\0')
		{
			return(&str[i]);
		}
		i++;

	}
	return(0);
}

int	main(void)
{
	char	*result;

	result = ft_strstr("abxac", "abc");

	if (result != 0)
		printf("Found: %s\n", result);
	else
		printf("Not found\n");

	return (0);
}
