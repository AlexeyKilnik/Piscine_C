
/*
 * C04 — ex01: ft_putstr
 *
 * ЗАДАНИЕ:
 * Напиши функцию, которая выводит
 * переданную строку в терминал.
 *
 * Для вывода используй write().
 * Выводи строку посимвольно.
 *
 * ПРИМЕРЫ:
 * "Hello"     -> Hello
 * "42 School" -> 42 School
 * ""          -> ничего
 *
 * ОЖИДАЕМАЯ ЛОГИКА:
 * 1. Начни с первого символа строки.
 * 2. Проверь, не равен ли он '\0'.
 * 3. Если нет — выведи символ через write().
 * 4. Перейди к следующему символу.
 * 5. Повторяй до конца строки.
 *
 * ЗАПРЕЩЕНО:
 * Использовать printf() или puts().
 * Не добавляй перевод строки автоматически.
 */

#include <unistd.h>

void ft_putstr(char *str)
{
    // Напиши решение здесь
    int i;

    i = 0;

    while (str[i] != '\0')
    {
    	write(1, &str[i],1);
	i++;
    }
}

int main(void)
{
    ft_putstr("Hello\n");
    ft_putstr("Football\n");
    ft_putstr("42 School\n");
    ft_putstr("");

    return (0);
}
