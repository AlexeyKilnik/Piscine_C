
/*
 * C04 — ex00: ft_strlen
 *
 * ЗАДАНИЕ:
 * Напиши функцию, которая подсчитывает
 * количество символов в строке.
 *
 * Функция должна вернуть длину строки,
 * не учитывая завершающий символ '\0'.
 *
 * ПРИМЕРЫ:
 * "Hello"       -> 5
 * "Football"    -> 8
 * "42 School"   -> 9
 * ""            -> 0
 *
 * ОЖИДАЕМАЯ ЛОГИКА:
 * 1. Создай счётчик символов.
 * 2. Начни с первого символа строки.
 * 3. Пока не встретишь '\0',
 *    увеличивай счётчик.
 * 4. Верни количество символов.
 *
 * ЗАПРЕЩЕНО:
 * Использовать готовую функцию strlen().
 */
#include <stdio.h>

int ft_strlen(char *str)
{
    // Напиши решение здесь
    int i;

    i = 0;

    while (str[i] != '\0')
    {
    	i++;
    }
    return(i);
}

int main(void)
{
	printf("Hello: %d\n", ft_strlen("Hello"));
	return(1);
}

